#!/bin/sh
# import-freebsd.sh — copy LinuxKPI (and later mt76) from a FreeBSD checkout at
# a pinned commit into haiku/src/..., and regenerate IMPORTED.md provenance.
#
# Usage: FREEBSD_TOP=/path/to/freebsd-src tools/import-freebsd.sh
# The checkout must be at $FREEBSD_COMMIT (see below) or the script refuses.
set -eu
FREEBSD_COMMIT=${FREEBSD_COMMIT:-b556d9c9ce94a6c9b6e28e8ecef7cc252531e91c}
FREEBSD_TOP=${FREEBSD_TOP:?set FREEBSD_TOP}
REPO=$(cd "$(dirname "$0")/.." && pwd)
have=$(git -C "$FREEBSD_TOP" rev-parse HEAD)
[ "$have" = "$FREEBSD_COMMIT" ] || { echo "FreeBSD checkout is $have, want $FREEBSD_COMMIT" >&2; exit 1; }

LK=$REPO/haiku/src/libs/compat/linuxkpi
LKW=$REPO/haiku/src/libs/compat/linuxkpi_wlan
SRC=$FREEBSD_TOP/sys/compat/linuxkpi/common

# Wifi-relevant LinuxKPI sources (docs/RESEARCH.md §3.1). Headers: all of them.
CORE="linux_compat.c linux_current.c linux_devres.c linux_domain.c linux_firmware.c
 linux_hrtimer.c linux_idr.c linux_interrupt.c linux_kmod.c linux_kobject.c
 linux_kthread.c linux_lock.c linux_netdev.c linux_page.c linuxkpi_page_pool.c
 linux_pci.c linux_radix.c linux_rcu.c linux_schedule.c linux_skbuff.c linux_slab.c
 linux_tasklet.c linux_timesub.c linux_work.c linux_xarray.c"
WLAN="linux_80211.c linux_80211.h linux_80211_macops.c linuxkpi_80211_pm.c"

rm -rf "$LK/common" "$LKW/imported"
mkdir -p "$LK/common/src" "$LKW/imported"
cp -R "$SRC/include" "$LK/common/include"
for f in $CORE; do cp "$SRC/src/$f" "$LK/common/src/"; done
for f in $WLAN; do cp "$SRC/src/$f" "$LKW/imported/"; done

# Verbatim FreeBSD kernel headers/sources LinuxKPI needs that Haiku's
# freebsd_network lacks (header-only or self-contained).
FB=$LK/freebsd
rm -rf "$FB"; mkdir -p "$FB/include/sys" "$FB/src"
for h in sys/tree.h sys/rtprio.h sys/gsb_crc32.h; do
	cp "$FREEBSD_TOP/sys/$h" "$FB/include/$h"
done
# ConcurrencyKit (BSD-2-Clause): headers + ck_epoch.c, for linux_rcu.c.
mkdir -p "$FB/ck/src"
cp -R "$FREEBSD_TOP/sys/contrib/ck/include" "$FB/ck/include"
cp "$FREEBSD_TOP/sys/contrib/ck/src/ck_epoch.c" "$FB/ck/src/"
# crc32_tab[] only: the rest of gsb_crc32.c is CRC32C with x86 SSE4.2 paths.
{
	sed -n '1,/^ \*\//p' "$FREEBSD_TOP/sys/libkern/gsb_crc32.c"
	echo
	echo "/* Extracted by tools/import-freebsd.sh: crc32_tab[] from"
	echo " * sys/libkern/gsb_crc32.c (table only). */"
	echo "#include <sys/types.h>"
	echo
	sed -n '/^const uint32_t crc32_tab\[\]/,/^};/p' "$FREEBSD_TOP/sys/libkern/gsb_crc32.c"
} > "$FB/src/gsb_crc32_tab.c"

spdx() { grep -m1 -o 'SPDX-License-Identifier:.*' "$1" 2>/dev/null | sed 's/SPDX-License-Identifier: *//; s/ *\*\/.*//' || true; }
lic() {
	s=$(spdx "$1"); [ -n "$s" ] && { echo "$s"; return; }
	if grep -q "Distributed under the terms of the MIT License\|Copyright 2026, LinuxKPI_HaikuOS contributors. MIT" "$1" && \
	    ! grep -q "Redistribution and use" "$1"; then
		echo "MIT"
	elif grep -q "Redistribution and use in source and binary forms" "$1"; then
		if grep -q "3\. Neither the name\|3\. The name" "$1"; then echo "BSD-3-Clause (text)"; else echo "BSD-2-Clause (text)"; fi
	else echo "**NO LICENSE TEXT — review**"; fi
}
{
	echo "# Imported files"
	echo
	echo "Generated by \`tools/import-freebsd.sh\`. Do not edit by hand."
	echo
	echo "Source: https://github.com/freebsd/freebsd-src at \`$FREEBSD_COMMIT\`"
	echo "($(git -C "$FREEBSD_TOP" log -1 --format=%cd --date=short))."
	echo
	echo "| Path in this repo | FreeBSD path | License |"
	echo "|---|---|---|"
	for f in $(cd "$LK/common" && find . -type f | sort); do
		f=${f#./}
		case $f in src/*) up=sys/compat/linuxkpi/common/src/${f#src/} ;; *) up=sys/compat/linuxkpi/common/$f ;; esac
		echo "| linuxkpi/common/$f | $up | $(lic "$LK/common/$f") |"
	done
	for f in $(cd "$FB" && find . -type f | sort); do
		f=${f#./}
		case $f in include/*) up=sys/${f#include/} ;; ck/*) up=sys/contrib/ck/${f#ck/} ;; src/gsb_crc32_tab.c) up="sys/libkern/gsb_crc32.c (crc32_tab only)" ;; esac
		echo "| linuxkpi/freebsd/$f | $up | $(lic "$FB/$f") |"
	done
	for f in $WLAN; do
		echo "| linuxkpi_wlan/imported/$f | sys/compat/linuxkpi/common/src/$f | $(lic "$LKW/imported/$f") |"
	done
	echo
	echo "## Generated from imported files"
	echo
	echo "Regenerate after every import; both scripts fail if FreeBSD changed an adapted spot."
	echo
	echo "| File | From | Tool |"
	echo "|---|---|---|"
	echo "| linuxkpi/haiku/lkpi_compat.c | common/src/linux_compat.c (generic part, verbatim) | tools/extract-compat.py |"
	echo "| linuxkpi/haiku/lkpi_rcu.c | common/src/linux_rcu.c (2 adaptations) | tools/derive.py |"
	echo
	echo "## Written for Haiku (MIT unless the file says otherwise)"
	echo
	echo "lkpi_pci.c is derived from FreeBSD linux_pci.c and keeps its BSD-2-Clause notice."
	echo
	echo "| File | License |"
	echo "|---|---|"
	for f in $(cd "$LK/haiku" && find . -type f | sort); do
		f=${f#./}
		case $f in lkpi_compat.c|lkpi_rcu.c) continue ;; esac
		echo "| linuxkpi/haiku/$f | $(lic "$LK/haiku/$f") |"
	done
} > "$REPO/IMPORTED.md"
echo "imported $(cd "$LK/common" && find . -type f | wc -l) files; see IMPORTED.md"
